-- 1. LISTAR TODAS LAS TABLAS
SELECT '=== TABLAS ===' as Info;
SELECT 
    TABLE_SCHEMA,
    TABLE_NAME,
    TABLE_TYPE
FROM INFORMATION_SCHEMA.TABLES 
WHERE TABLE_TYPE = 'BASE TABLE' 
    AND TABLE_SCHEMA = 'dbo'
ORDER BY TABLE_NAME;

-- 2. ESTRUCTURA DE TABLAS PRINCIPALES (PALETS RELACIONADAS)
SELECT '=== ESTRUCTURA TABLA PALETS ===' as Info;
SELECT 
    COLUMN_NAME,
    DATA_TYPE,
    CHARACTER_MAXIMUM_LENGTH,
    NUMERIC_PRECISION,
    NUMERIC_SCALE,
    IS_NULLABLE,
    COLUMN_DEFAULT
FROM INFORMATION_SCHEMA.COLUMNS 
WHERE TABLE_NAME = 'Palets' 
    AND TABLE_SCHEMA = 'dbo'
ORDER BY ORDINAL_POSITION;

SELECT '=== ESTRUCTURA TABLA PALETCOMPOSICION ===' as Info;
SELECT 
