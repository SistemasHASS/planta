-- 4. LISTAR TABLAS DE CATÁLOGOS
SELECT '=== TABLAS DE CATÁLOGOS ===' as Info;
SELECT 
    TABLE_NAME
FROM INFORMATION_SCHEMA.TABLES 
WHERE TABLE_TYPE = 'BASE TABLE' 
    AND TABLE_SCHEMA = 'dbo'
    AND (
        TABLE_NAME LIKE '%Cliente%' 
        OR TABLE_NAME LIKE '%Consignatario%'
        OR TABLE_NAME LIKE '%Destino%'
        OR TABLE_NAME LIKE '%Variedad%'
        OR TABLE_NAME LIKE '%Calibre%'
        OR TABLE_NAME LIKE '%Empaque%'
        OR TABLE_NAME LIKE '%Caja%'
        OR TABLE_NAME LIKE '%Clamshell%'
        OR TABLE_NAME LIKE '%Presentacion%'
        OR TABLE_NAME LIKE '%Produccion%'
        OR TABLE_NAME LIKE '%Rancho%'
        OR TABLE_NAME LIKE '%Transporte%'
        OR TABLE_NAME LIKE '%Categoria%'
        OR TABLE_NAME LIKE '%Campania%'
    )
ORDER BY TABLE_NAME;

-- 5. STORED PROCEDURES EXISTENTES
SELECT '=== STORED PROCEDURES EXISTENTES ===' as Info;
SELECT 
    name,
    create_date,
    modify_date
FROM sys.procedures 
WHERE name LIKE '%Palet%' 
    OR name LIKE '%palet%'
    OR name LIKE '%Composicion%'
ORDER BY name;

-- 6. REVISAR SI EXISTEN LAS TABLAS PRINCIPALES
SELECT '=== VERIFICACIÓN DE TABLAS PRINCIPALES ===' as Info;
SELECT 
    CASE 
        WHEN EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'Palets') 
        THEN 'EXISTS' 
        ELSE 'MISSING' 
    END as Palets,
    CASE 
        WHEN EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'PaletComposicion') 
        THEN 'EXISTS' 
        ELSE 'MISSING' 
    END as PaletComposicion,
    CASE 
        WHEN EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'Procesos') 
        THEN 'EXISTS' 
        ELSE 'MISSING' 
    END as Procesos,
    CASE 
        WHEN EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'Acopios') 
        THEN 'EXISTS' 
        ELSE 'MISSING' 
    END as Acopios,
    CASE 
        WHEN EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'Formatos') 
        THEN 'EXISTS' 
        ELSE 'MISSING' 
    END as Formatos;
